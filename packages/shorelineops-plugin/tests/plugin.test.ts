import test from 'node:test';
import { z } from 'zod';
import assert from 'node:assert/strict';
import { promises as fs } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { StdioClientTransport, getDefaultEnvironment } from '@modelcontextprotocol/sdk/client/stdio.js';
import { CampusProfileSchema } from '../src/campus/index.js';
import { makeValidMenu } from './helpers.js';

test('packaged MCP server discovers tools, preserves approval gates, and serves deterministic PDF resources', async t => {
  const directory = await fs.mkdtemp(path.join(os.tmpdir(),'sylvia-mcp-'));
  const client = new Client({name:'sylvia-plugin-verifier',version:'0.2.0'},{capabilities:{}});
  const transport = new StdioClientTransport({command:process.execPath,args:[path.resolve('plugin/server.mjs')],cwd:path.resolve('plugin'),env:{...getDefaultEnvironment(),LOCALAPPDATA:process.env.LOCALAPPDATA || path.join(os.homedir(),'AppData','Local'),SYLVIA_DATA_DIR:directory},stderr:'pipe'});
  let errors = '';
  transport.stderr?.on('data',data => { errors+=String(data); });
  t.after(async()=>{ await client.close(); await fs.rm(directory,{recursive:true,force:true}); });
  await client.connect(transport);
 await client.callTool({name:'campus_configure',arguments:{profile:JSON.parse(await fs.readFile('fixtures/campus-profile.json','utf8')),confirmed:true,confirmed_by:'SYNTHETIC TEST SETUP'}});
  const tools = await client.listTools();
  assert.deepEqual(tools.tools.map(tool=>tool.name).sort(),['facility_setup','shoreline_status','campus_assign_menu','campus_configure','campus_packet_generate','campus_review','count_scan_block','count_scan_confirm','count_scan_correct','count_scan_for_menu','count_scan_import','count_scan_review','menu_approve','menu_correct','menu_export','menu_import','menu_privacy_review','menu_readiness','menu_review','packet_generate','ross_worksheet_generate','sylvia_status','work_area_generate','workflow_status'].sort());
  const campus = await client.callTool({name:'campus_review',arguments:{}});
  assert.equal(campus.isError,undefined,JSON.stringify(campus));
  const campusProfile = z.object({profile:z.object({status:z.literal('confirmed'),residentAreas:z.array(z.object({id:z.string()}))})}).parse(campus.structuredContent);
  assert.equal(campusProfile.profile.residentAreas.length,3);
  const crossWing = await client.callTool({name:'packet_generate',arguments:{menu_id:'week-1-example',resident_area_id:'ross_manor'}});
  assert.equal(crossWing.isError,true);
  const unconfirmedSharing = await client.callTool({name:'campus_assign_menu',arguments:{menu_id:'week-1-example',resident_area_ids:['ross_manor'],confirmed:false,confirmed_by:'SYNTHETIC TEST ONLY'}});
  assert.equal(unconfirmedSharing.isError,true);
  const workLog = await client.callTool({name:'work_area_generate',arguments:{work_area_id:'ross_hot',date:'2026-10-25'}});
  assert.equal(workLog.isError,undefined,JSON.stringify(workLog));
  const workInfo = JSON.parse((workLog.content as {text:string}[])[0]!.text) as {pages:number};
  assert.equal(workInfo.pages,1);
  for(const format of ['prep-list','meal-service']){
    const worksheet=await client.callTool({name:'ross_worksheet_generate',arguments:{format,resident_area_id:'ross_manor',date:'2026-10-29'}});
    assert.equal(worksheet.isError,undefined,JSON.stringify(worksheet));
    const sheet=JSON.parse((worksheet.content as {text:string}[])[0]!.text) as {pages:number;resource_uri:string};
    assert.equal(sheet.pages,1);assert.ok((await client.readResource({uri:sheet.resource_uri})).contents.length);
  }
  const residentInput=await client.callTool({name:'ross_worksheet_generate',arguments:{format:'meal-service',resident_area_id:'ross_manor',date:'2026-10-29',resident_name:'SYNTHETIC NAME'}});
  // Host schema exposes no resident parameters; unknown values must never enter the renderer.
  if(!residentInput.isError)assert.ok(!JSON.stringify(residentInput).includes('SYNTHETIC NAME'));
  const status = await client.callTool({name:'sylvia_status',arguments:{}});
  assert.equal(status.isError,undefined,errors);
  const manifest=JSON.parse(await fs.readFile('plugin/plugin.json','utf8')) as {version:string};
  assert.equal(z.object({version:z.string()}).parse(status.structuredContent).version,manifest.version);
  assert.equal(client.getServerVersion()?.version,manifest.version);
  const review = await client.callTool({name:'menu_review',arguments:{menu_id:'week-1-example'}});
  assert.equal(review.isError,undefined,JSON.stringify(review));
  assert.equal(z.object({approved:z.boolean()}).parse(review.structuredContent).approved,false);
  const exported=await client.callTool({name:'menu_export',arguments:{menu_id:'week-1-example'}});
  assert.equal(exported.isError,undefined,JSON.stringify(exported));
  const exportInfo=JSON.parse((exported.content as {text:string}[])[0]!.text) as {resource_uri:string};
  const transferResource=await client.readResource({uri:exportInfo.resource_uri});
  const transfer=JSON.parse((transferResource.contents[0] as {text:string}).text) as {menu:{approval:unknown;source:{file:string}}};
  assert.equal(transfer.menu.approval,null);assert.match(transfer.menu.source.file,/^menu-source\./);
  const denied = await client.callTool({name:'packet_generate',arguments:{menu_id:'week-1-example',preview:false}});
  assert.equal(denied.isError,true,'Unapproved real menu must never produce production output');
  const weekly = await client.callTool({name:'packet_generate',arguments:{menu_id:'week-1-example'}});
  assert.equal(weekly.isError,undefined,JSON.stringify(weekly));
  const info = JSON.parse((weekly.content as {type:string;text?:string}[])[0]!.text!) as {pages:number;resource_uri:string};
  assert.equal(info.pages,2);
  const resource = await client.readResource({uri:info.resource_uri});
  const blob = resource.contents[0] as {blob:string;mimeType:string};
  assert.equal(blob.mimeType,'application/pdf');
  assert.equal(Buffer.from(blob.blob,'base64').subarray(0,5).toString(),'%PDF-');
  const badDate = await client.callTool({name:'packet_generate',arguments:{menu_id:'week-1-example',packet:'daily',date:'2026-11-01'}});
  assert.equal(badDate.isError,true);
  const pathTraversal = await client.readResource({uri:'sylvia-ross://packets/..%2Fsecret'}).then(()=>false,()=>true);
  assert.equal(pathTraversal,true);
  const outside = await client.callTool({name:'menu_import',arguments:{source_path:path.resolve('package.json'),menu:((({source:_source,approval:_approval,...rest})=>rest)(makeValidMenu()))}});
  assert.equal(outside.isError,true,'Arbitrary local file imports must fail');
  // Approve only a synthetic fixture paired with a synthetic 1x1 PNG, never the real menu.
  const sourceDirectory = path.join(directory,'sources');
  await fs.mkdir(sourceDirectory,{recursive:true});
  const image = path.join(sourceDirectory,'synthetic.png');
  await fs.writeFile(image,Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jp1sAAAAASUVORK5CYII=','base64'));
  const {source:_source,approval:_approval,...synthetic} = makeValidMenu();
  const missingPrivacy=await client.callTool({name:'menu_import',arguments:{source_path:image,menu:synthetic}});
  assert.equal(missingPrivacy.isError,true);
  await assert.rejects(fs.readdir(path.join(directory,'menus')));
  const imported = await client.callTool({name:'menu_import',arguments:{source_path:image,menu:synthetic,privacy_review:{source_content_reviewed:true,source_filename_reviewed:true,resident_information_found:false}}});
  assert.equal(imported.isError,undefined,JSON.stringify(imported));
  const id = z.object({menu_id:z.string()}).parse(imported.structuredContent).menu_id;
  assert.match(id,/^menu-[a-f0-9]{64}$/);
  const initialCampus=z.object({profile:CampusProfileSchema}).parse(campus.structuredContent).profile;
  initialCampus.name='SYNTHETIC CAMPUS'; initialCampus.source='Synthetic integration test only';
  const unconfirmedConfig=await client.callTool({name:'campus_configure',arguments:{profile:initialCampus,confirmed:false,confirmed_by:'SYNTHETIC TEST ONLY'}});
  assert.equal(unconfirmedConfig.isError,true);
  const configured=await client.callTool({name:'campus_configure',arguments:{profile:initialCampus,confirmed:true,confirmed_by:'SYNTHETIC TEST ONLY'}});
  assert.equal(configured.isError,undefined,JSON.stringify(configured));
  const assignment=await client.callTool({name:'campus_assign_menu',arguments:{menu_id:id,resident_area_ids:['ross_manor'],confirmed:true,confirmed_by:'SYNTHETIC TEST ONLY'}});
  assert.equal(assignment.isError,undefined,JSON.stringify(assignment));
  const scoped=await client.callTool({name:'packet_generate',arguments:{menu_id:id,resident_area_id:'ross_manor'}});
  assert.equal(scoped.isError,undefined,JSON.stringify(scoped));
  const forbiddenConfig=await client.callTool({name:'campus_configure',arguments:{profile:initialCampus,confirmed:true,confirmed_by:'SYNTHETIC TEST ONLY'}});
  assert.equal(forbiddenConfig.isError,true,'General configuration must not erase explicit sharing');
  const scopedInfo=JSON.parse((scoped.content as {text:string}[])[0]!.text) as {resource_uri:string};
  await client.callTool({name:'campus_assign_menu',arguments:{menu_id:id,resident_area_ids:['sylvia_ross'],confirmed:true,confirmed_by:'SYNTHETIC TEST ONLY'}});
  await assert.rejects(client.readResource({uri:scopedInfo.resource_uri}),'Revoked sharing must stop serving the old shared PDF');
  const refuse = await client.callTool({name:'menu_approve',arguments:{menu_id:id,reviewer:'SYNTHETIC TEST ONLY',confirmed_all_42_options:false}});
  assert.equal(refuse.isError,true);
  const approved = await client.callTool({name:'menu_approve',arguments:{menu_id:id,reviewer:'SYNTHETIC TEST ONLY',confirmed_all_42_options:true}});
  assert.equal(approved.isError,undefined,JSON.stringify(approved));
  const production = await client.callTool({name:'packet_generate',arguments:{menu_id:id,preview:false,packet:'daily',date:'2026-10-25'}});
  assert.equal(production.isError,undefined,JSON.stringify(production));
  const productionInfo = JSON.parse((production.content as {text:string}[])[0]!.text) as {pages:number;preview:boolean};
  assert.equal(productionInfo.pages,3);
  assert.equal(productionInfo.preview,false);
  const correction=await client.callTool({name:'menu_correct',arguments:{menu_id:id,privacy_review:{source_content_reviewed:true,source_filename_reviewed:true,resident_information_found:false},changes:[{field:'days[0].meals.breakfast.a.items[0].text',value:'Synthetic replacement',needs_review:false}]}});
  assert.equal(correction.isError,undefined,JSON.stringify(correction));
  const corrected=z.object({menu_id:z.string(),approved:z.boolean()}).parse(correction.structuredContent);
  assert.notEqual(corrected.menu_id,id);assert.equal(corrected.approved,false);
  const correctedDenied=await client.callTool({name:'packet_generate',arguments:{menu_id:corrected.menu_id,preview:false}});
  assert.equal(correctedDenied.isError,true);
  const blocked=await client.callTool({name:'menu_privacy_review',arguments:{menu_id:id,privacy_review:{source_content_reviewed:true,source_filename_reviewed:true,resident_information_found:true}}});
  assert.equal(blocked.isError,undefined);
  const blockedRead=await client.callTool({name:'menu_review',arguments:{menu_id:id,detail:'full'}});
  assert.equal(blockedRead.isError,true);
  const blockedPrint=await client.callTool({name:'packet_generate',arguments:{menu_id:id}});
  assert.equal(blockedPrint.isError,true);
  const productionMeta=JSON.parse((production.content as {text:string}[])[0]!.text) as {resource_uri:string};
  await assert.rejects(client.readResource({uri:productionMeta.resource_uri}));
  const blockedExport=await client.callTool({name:'menu_export',arguments:{menu_id:id}});
  assert.equal(blockedExport.isError,true,'Quarantined menus cannot be exported');
  await fs.writeFile(image,'tampered');
  // The imported original is a separate immutable, hash-addressed copy.
  const reread = await client.callTool({name:'menu_review',arguments:{menu_id:id}});
  assert.equal(reread.isError,undefined);
});
